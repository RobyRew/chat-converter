/*
 * Writes WhatsApp's chat export text (`_chat.txt`) and plans the media entries that go with it.
 *
 * Byte rules, taken from real WhatsApp 2026 exports (iOS/macOS):
 * - UTF-8, no BOM. Every message ends with CRLF; line breaks inside a message are a bare LF.
 * - `[DD/MM/YYYY, HH:MM:SS] Name: text`, local wall-clock time, 24 h.
 * - A line that carries media starts with U+200E (LRM) before `[`; the reference is the caption, a
 *   space, then `‎<attached: NNNNNNNN-PHOTO-YYYY-MM-DD-HH-MM-SS.jpg>`. Media that is not in the
 *   export becomes a marker in the same position: `‎image omitted`, `‎video omitted`, …
 * - Polls: `‎POLL:\n<question>\n‎OPTION: <text> (<n> votes)`.
 * - The first line is the end-to-end-encryption notice, attributed to the chat title (the group name,
 *   or the other person in a private chat).
 * - Media names: `NNNNNNNN-{PHOTO|VIDEO|AUDIO|STICKER|GIF}-<time>.<ext>`; documents keep their name
 *   after the number; contacts are `.vcf`.
 *
 * The `telegram` flavor follows Telegram's importer instead of WhatsApp where they differ
 * (Telegram-iOS ShareExtensionContext.swift / ChatImportActivityScreen.swift @ 24638bc):
 * - entry types come from the name: `.*?\.jpg` photo, `\d+-VIDEO-.*?\.mp4` video,
 *   `\d+-STICKER-.*?\.webp` sticker, `\d+-AUDIO-.*?\.opus` voice, anything else a file. iOS has no
 *   GIF type, so animations are written as `-VIDEO-` to play inline instead of landing as a file.
 */

export const LRM = '‎';
const ZWSP = '​';
const CRLF = '\r\n';

/** The notice text of current WhatsApp exports. */
export const E2E_NOTICE =
  'Messages and calls are end-to-end encrypted. Only people in this chat can read, listen to, or share them.';
const E2E_PREFIX = /^Messages and calls are end-to-end encrypted\b/;

export type WhatsAppFlavor = 'whatsapp' | 'telegram';

export interface PlannedMedia {
  /** Archive entry name, also used in `<attached: …>`. */
  name: string;
  /** Source path of the bytes; absent for generated content. */
  ref?: string;
  /** Generated bytes (vCards rebuilt from contact fields). */
  bytes?: Uint8Array;
  size: number;
  lastModified: Date;
}

export interface WhatsAppChat {
  /** `_chat.txt` content. */
  text: string;
  media: PlannedMedia[];
  /** Chat title used for the notice line and the archive name. */
  title: string;
  mode: 'dm' | 'group';
  selfId?: string;
  messagesIn: number;
  /** Message lines written, notice lines excluded. */
  messagesOut: number;
  /** Notice lines added on top (end-to-end notice, group creation). */
  headerLines: number;
  mediaOmitted: number;
  dropped: Record<string, number>;
  approximated: Record<string, number>;
  warnings: string[];
}

export interface BuildOptions extends WhatsAppPackageOptions {
  flavor: WhatsAppFlavor;
  /** Write `<attached:>` references with planned media (packages); otherwise only WhatsApp-named originals. */
  includeMedia: boolean;
  media?: MediaStore;
  title?: string;
}

const pad = (n: number, w = 2): string => String(n).padStart(w, '0');

function stamp(w: WallClock): string {
  return `[${pad(w.day)}/${pad(w.month)}/${pad(w.year, 4)}, ${pad(w.hour)}:${pad(w.minute)}:${pad(w.second)}]`;
}

function fileStamp(w: WallClock): string {
  return `${pad(w.year, 4)}-${pad(w.month)}-${pad(w.day)}-${pad(w.hour)}-${pad(w.minute)}-${pad(w.second)}`;
}

/** Names may not contain `:` (it separates the sender) or line breaks. */
export function sanitizeName(name: string): string {
  const clean = name
    .replace(/[\r\n\u2028\u2029]+/g, ' ')
    .replace(/[‎‏‪-‮]/g, '')
    .replace(/:/g, '꞉')
    .replace(/\s+/g, ' ')
    .trim();
  return clean || 'Unknown';
}

/** Safe for a zip entry, for `<attached: …>` and for Telegram-Android's `fixFileName`. */
export function sanitizeFileName(name: string, max = 120): string {
  let n = name
    .replace(/[\u0000-\u001f\u007f‮<>:"/\\|?*]/g, '_')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^\.+/, '_');
  if (!n) n = 'file';
  if (n.length > max) {
    const ext = extensionOf(n);
    const keep = ext ? `.${ext}` : '';
    n = n.slice(0, max - keep.length) + keep;
  }
  return n;
}

/**
 * Keeps a document from being typed as photo/video/sticker/voice by Telegram-iOS's name regexes, and
 * from being taken for the main chat file (iOS: `_chat.txt`, `KakaoTalkChats.txt`, `Talk_*.txt`;
 * Android: the first `.txt`).
 */
export function neutralizeDocumentName(name: string, isJpeg: boolean): string {
  let n = name;
  if (!isJpeg) n = n.replace(/\.jpg/g, '_jpg');
  else n = n.replace(/\.jpg(?=.)/g, '_jpg');
  n = n.replace(/(\d)-(VIDEO|STICKER|AUDIO)-/g, '$1_$2_');
  n = n.replace(/_chat\.txt/g, '-chat.txt').replace(/KakaoTalkChats\.txt/g, 'KakaoTalkChats-.txt');
  n = n.replace(/Talk_(?=.*?\.txt)/g, 'Talk-');
  return n;
}

const OMITTED_LABEL: Record<Attachment['kind'], string> = {
  image: 'image omitted',
  video: 'video omitted',
  gif: 'GIF omitted',
  animation: 'GIF omitted',
  audio: 'audio omitted',
  voice: 'audio omitted',
  sticker: 'sticker omitted',
  file: 'document omitted',
  contact: 'Contact card omitted',
  location: 'document omitted',
  poll: 'document omitted',
  unknown: 'document omitted',
};

/** Telegram writes the deleted peer as "Deleted Account"; a DM's other side is the chat title. */
export function guessSelf(conv: Conversation): string | undefined {
  const people = conv.participants;
  // Account-wide exports (Instagram, Snapchat, VSCO, Hinge…) name the owner.
  if (conv.selfId && people.some((p) => p.id === conv.selfId)) return conv.selfId;
  if (people.length !== 2) return undefined;
  const [a, b] = people as [Participant, Participant];
  if (a.meta?.['deletedAccount']) return b.id;
  if (b.meta?.['deletedAccount']) return a.id;
  if (conv.title) {
    if (a.displayName === conv.title) return b.id;
    if (b.displayName === conv.title) return a.id;
  }
  return undefined;
}

function vcard(c: NonNullable<Message['contact']>): Uint8Array {
  const fn = [c.firstName, c.lastName].filter(Boolean).join(' ') || c.phone || 'Contact';
  const lines = [
    'BEGIN:VCARD',
    'VERSION:3.0',
    `N:${c.lastName ?? ''};${c.firstName ?? ''};;;`,
    `FN:${fn}`,
    ...(c.phone ? [`TEL;TYPE=CELL:${c.phone}`] : []),
    'END:VCARD',
    '',
  ];
  return new TextEncoder().encode(lines.join('\r\n'));
}

/** A continuation line that looks like a message header would be split off by any WhatsApp parser. */
const HEADER_LIKE = /^[‎‏]*(?:\[\d{1,4}[./-]\d{1,2}[./-]\d{1,4},? \d{1,2}:\d{2}|\d{1,4}[./-]\d{1,2}[./-]\d{1,4},? \d{1,2}:\d{2}(?::\d{2})?(?:\s?[APap]\.?\s?[Mm]\.?)? - )/;

function escapeBody(text: string): { text: string; escaped: number } {
  let escaped = 0;
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  for (let i = 1; i < lines.length; i++) {
    if (HEADER_LIKE.test(lines[i]!)) {
      lines[i] = ZWSP + lines[i]!;
      escaped++;
    }
  }
  return { text: lines.join('\n'), escaped };
}

const inc = (rec: Record<string, number>, key: string, n = 1): void => {
  rec[key] = (rec[key] ?? 0) + n;
};

/** Builds `_chat.txt` and the media plan for one conversation. */
export function buildWhatsAppChat(conv: Conversation, opts: BuildOptions): WhatsAppChat {
  const tz = opts.timeZone ?? defaultTimeZone();
  const flavor = opts.flavor;
  const mode: 'dm' | 'group' = opts.mode ?? (conv.kind === 'dm' ? 'dm' : 'group');
  const selfId = opts.selfId ?? guessSelf(conv);
  const serviceAsText = opts.serviceAsText ?? true;
  const omittedMarkers = opts.omittedMarkers ?? true;
  const animated = opts.animatedStickers ?? 'omit';
  const fromWhatsApp = conv.originPlatform === 'whatsapp';

  const names = new Map<string, string>();
  for (const p of conv.participants) names.set(p.id, sanitizeName(p.displayName ?? p.id));
  const peer = conv.participants.find((p) => p.id !== selfId) ?? conv.participants[0];
  const title =
    mode === 'dm'
      ? sanitizeName(peer?.displayName ?? opts.title ?? conv.title ?? 'Chat')
      : sanitizeName(opts.title ?? conv.title ?? 'Group');
  const selfName = selfId ? (names.get(selfId) ?? title) : undefined;

  const dropped: Record<string, number> = {};
  const approximated: Record<string, number> = {};
  const warnings: string[] = [];
  const media: PlannedMedia[] = [];
  const used = new Set<string>();
  const out: string[] = [];
  let messagesOut = 0;
  let headerLines = 0;
  let mediaOmitted = 0;

  const offsetFor = (m: Message): number => m.tzOffsetMinutes ?? zoneOffsetMinutes(m.ts, tz);
  const wallFor = (m: Message): WallClock => wallClockAt(m.ts, offsetFor(m));

  const uniqueName = (name: string): string => {
    if (!used.has(name)) {
      used.add(name);
      return name;
    }
    const ext = extensionOf(name);
    const stem = ext ? name.slice(0, -(ext.length + 1)) : name;
    for (let i = 2; ; i++) {
      const candidate = ext ? `${stem}-${i}.${ext}` : `${stem}-${i}`;
      if (!used.has(candidate)) {
        used.add(candidate);
        return candidate;
      }
    }
  };

  const first = conv.messages[0];
  const firstIsNotice = !!first && (wa(first)['notice'] === true || E2E_PREFIX.test(first.content?.text ?? ''));
  // A WhatsApp source is written back in its own header style and line ending; packages for Telegram
  // reuse raw bodies only from iOS-style files, whose markers match the iOS header.
  const sourceStyle = fromWhatsApp && conv.ext?.['whatsapp']?.['headerStyle'] === 'android' ? 'android' : 'ios';
  const rawAllowed = fromWhatsApp && (flavor === 'whatsapp' || sourceStyle === 'ios');
  const eol = flavor === 'whatsapp' && fromWhatsApp && conv.ext?.['whatsapp']?.['eol'] === '\n' ? '\n' : CRLF;
  if ((opts.noticeLine ?? true) && first && !firstIsNotice) {
    const s = stamp(wallFor(first));
    out.push(`${s} ${title}: ${LRM}${E2E_NOTICE}${CRLF}`);
    headerLines++;
    if (mode === 'group' && selfName) {
      out.push(`${s} ${selfName}: ${LRM}${selfName} created this group${CRLF}`);
      headerLines++;
    }
  }

  conv.messages.forEach((m, index) => {
    const seq = String(index + 1).padStart(8, '0');
    const w = wallFor(m);
    const when = new Date(Date.UTC(w.year, w.month - 1, w.day, w.hour, w.minute, w.second));
    const isEvent = m.kind === 'service' || m.kind === 'call';
    if (isEvent && !serviceAsText) {
      inc(dropped, m.kind === 'call' ? 'calls' : 'serviceEvents');
      return;
    }
    const sender = m.senderId ? (names.get(m.senderId) ?? 'Unknown') : title;

    // A WhatsApp message whose text is unchanged is written back exactly as it was read (marks
    // included); only attachment names that this package changes are substituted.
    const raw = rawAllowed ? rawBodyOf(m) : undefined;
    if (raw !== undefined) {
      let body = raw;
      for (const a of m.attachments ?? []) {
        if (!a.fileName) continue; // an "omitted" marker, already in the raw text
        const source = a.ref && a.present !== false ? opts.media?.get(a.ref) : undefined;
        // The tag is in the phone's language (`<attached: …>`, `<adjunto: …>`…); keep it, swap the name.
        const reference = new RegExp(`(\u200e?)<([^<>:\n]{2,40}):(\\s*)${escapeRegExp(a.fileName)}>`);
        if (!opts.includeMedia) continue;
        if (!source || source.size === 0) {
          body = body.replace(reference, `${LRM}${OMITTED_LABEL[a.kind]}`);
          mediaOmitted++;
          continue;
        }
        const name = uniqueName(entryName(a, source.path, seq, w, flavor, true, false));
        media.push({ name, ref: source.path, size: source.size, lastModified: when });
        if (name !== a.fileName) body = body.replace(reference, (_m, lead: string, tag: string, gap: string) => `${lead}<${tag}:${gap}${name}>`);
      }
      const rawSender = typeof wa(m)['sender'] === 'string' ? (wa(m)['sender'] as string) : undefined;
      const attributed = typeof wa(m)['attributedTo'] === 'string' ? (wa(m)['attributedTo'] as string) : undefined;
      // The sender as written (WhatsApp writes non-contacts as "~\u202fName") unless it was renamed since.
      const current = m.senderId ? conv.participants.find((p) => p.id === m.senderId)?.displayName : undefined;
      const unchanged = rawSender !== undefined && current !== undefined && rawSender.replace(/[\u200e\u200f\u202a-\u202e\ufeff]/g, '') === current;
      const who = m.senderId ? (unchanged ? rawSender : sender) : (rawSender ?? attributed ?? title);
      const lead = wa(m)['lead'] ? LRM : '';
      const original = typeof wa(m)['stamp'] === 'string' ? (wa(m)['stamp'] as string) : undefined;
      const head =
        flavor === 'whatsapp' && sourceStyle === 'android' && original
          ? `${original} - ${who}`
          : `${original && (flavor === 'whatsapp' || sourceStyle === 'ios') ? `[${original}]` : stamp(w)} ${who}`;
      out.push(body ? `${lead}${head}: ${body}${eol}` : `${lead}${head}:${eol}`);
      messagesOut++;
      return;
    }

    // ----- text part -----
    let caption = '';
    if (m.poll) {
      const opt = m.poll.options.map((o) => {
        const v = o.votes ?? 0;
        return `${LRM}OPTION: ${o.text} (${v} ${v === 1 ? 'vote' : 'votes'})`;
      });
      caption = [`${LRM}POLL:`, m.poll.question, ...opt].join('\n');
      if (m.poll.options.some((o) => o.chosen)) inc(dropped, 'pollChoices');
    } else if (m.checklist) {
      caption = [`☑️ ${m.checklist.title}`, ...m.checklist.items.map((i) => `• ${i.text}`)].join('\n');
      inc(approximated, 'checklists');
    } else if (m.kind === 'call') {
      caption = m.call ? callText(m.call) : (m.content?.text ?? '📞 Call');
      inc(approximated, 'calls');
    } else if (m.kind === 'service') {
      caption = m.content?.text ?? (m.service?.action ?? 'service').replace(/_/g, ' ');
      inc(approximated, 'serviceEvents');
    } else if (m.location) {
      // Telegram location messages carry no caption; `content` only holds the importer's readable fallback.
      const label = [m.location.name, m.location.address].filter(Boolean).join(', ');
      caption = `${label ? `${label}\n` : ''}${LRM}Location: https://maps.google.com/?q=${m.location.lat},${m.location.lng}`;
      if (m.location.live) inc(approximated, 'liveLocations');
    } else if (m.contact && !m.attachments?.length) {
      caption = '';
    } else {
      caption = renderWhatsApp(m.content);
      const lost = (m.content?.entities ?? []).filter(
        (e) => !['bold', 'italic', 'strikethrough', 'code', 'pre'].includes(e.type),
      ).length;
      if (lost) inc(approximated, 'formatting', lost);
    }
    if (m.forwardedFrom) {
      if (opts.forwardLabels) caption = `Forwarded from ${m.forwardedFrom.name ?? 'someone'}:\n${caption}`;
      else inc(dropped, 'forwardLabels');
    }
    if (m.replyToId) {
      const target = opts.replyQuotes ? conv.messages.find((x) => x.id === m.replyToId) : undefined;
      const quoted = target?.content?.text?.split('\n')[0]?.slice(0, 100);
      if (quoted) caption = `> ${quoted}\n${caption}`;
      else inc(dropped, 'replies');
    }
    if (m.reactions?.length) inc(dropped, 'reactions', m.reactions.length);
    if (m.editedAt) {
      // WhatsApp's own exports carry the marker; Telegram's importer is not documented to read it.
      if (opts.editedMarker ?? flavor === 'whatsapp') caption = `${caption} ${LRM}<This message was edited>`;
      else inc(dropped, 'editMarks');
    }

    // ----- media part -----
    const refs: string[] = [];
    const attachments = [...(m.attachments ?? [])];
    for (const a of attachments) {
      const source = a.ref && a.present !== false ? opts.media?.get(a.ref) : undefined;
      const isAnimatedSticker = a.kind === 'sticker' && (a.stickerFormat === 'tgs' || a.stickerFormat === 'webm');
      if (isAnimatedSticker && animated === 'omit') {
        if (!caption && a.emoji) caption = a.emoji;
        refs.push(`${LRM}${OMITTED_LABEL.sticker}`);
        inc(approximated, 'animatedStickers');
        mediaOmitted++;
        continue;
      }
      if (!opts.includeMedia) {
        // Text-only export: keep references a WhatsApp export already had, mark everything else omitted.
        if (fromWhatsApp && a.fileName) refs.push(`${LRM}<attached: ${a.fileName}>`);
        else if (omittedMarkers) {
          refs.push(`${LRM}${OMITTED_LABEL[a.kind]}`);
          mediaOmitted++;
        }
        continue;
      }
      if (!source || source.size === 0) {
        if (omittedMarkers) refs.push(`${LRM}${OMITTED_LABEL[a.kind]}`);
        else inc(dropped, 'omittedMedia');
        mediaOmitted++;
        continue;
      }
      const name = uniqueName(entryName(a, source.path, seq, w, flavor, fromWhatsApp, isAnimatedSticker));
      media.push({ name, ref: source.path, size: source.size, lastModified: when });
      refs.push(`${LRM}<attached: ${name}>`);
    }

    // Contact cards: the exported vCard, else one rebuilt from the contact fields.
    if (m.contact) {
      const card = m.contact.vcardRef ? opts.media?.get(m.contact.vcardRef) : undefined;
      const label = sanitizeFileName([m.contact.firstName, m.contact.lastName].filter(Boolean).join(' ') || m.contact.phone || 'Contact');
      if (!opts.includeMedia) {
        if (omittedMarkers) {
          refs.push(`${LRM}${OMITTED_LABEL.contact}`);
          mediaOmitted++;
        }
      } else if (card && card.size > 0) {
        const name = uniqueName(`${seq}-${label}.vcf`);
        media.push({ name, ref: card.path, size: card.size, lastModified: when });
        refs.push(`${LRM}<attached: ${name}>`);
      } else {
        const bytes = vcard(m.contact);
        const name = uniqueName(`${seq}-${label}.vcf`);
        media.push({ name, bytes, size: bytes.byteLength, lastModified: when });
        refs.push(`${LRM}<attached: ${name}>`);
        inc(approximated, 'contactCardsRebuilt');
      }
    }

    // ----- assemble -----
    const { text: safeCaption, escaped } = escapeBody(caption);
    if (escaped) inc(approximated, 'headerLikeLines', escaped);
    let body = safeCaption;
    if (refs.length) body = body ? `${body} ${refs.join('\n')}` : refs.join('\n');
    const lead = refs.length ? LRM : '';
    out.push(body ? `${lead}${stamp(w)} ${sender}: ${body}${eol}` : `${lead}${stamp(w)} ${sender}:${eol}`);
    messagesOut++;
  });

  return {
    text: out.join(''),
    media,
    title,
    mode,
    ...(selfId ? { selfId } : {}),
    messagesIn: conv.messages.length,
    messagesOut,
    headerLines,
    mediaOmitted,
    dropped,
    approximated,
    warnings,
  };
}

/** The raw WhatsApp body kept by the importer, if the message text has not changed since. */
function rawBodyOf(m: Message): string | undefined {
  const raw = wa(m)['raw'];
  if (typeof raw !== 'string') return undefined;
  return wa(m)['contentText'] === (m.content?.text ?? '') ? raw : undefined;
}

/** The WhatsApp namespace of a message's extension data (`ext.whatsapp`). */
function wa(m: Message): Record<string, unknown> {
  return m.ext?.['whatsapp'] ?? {};
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Archive entry name for one attachment. */
function entryName(
  a: Attachment,
  sourcePath: string,
  seq: string,
  w: WallClock,
  flavor: WhatsAppFlavor,
  fromWhatsApp: boolean,
  animatedSticker: boolean,
): string {
  const t = fileStamp(w);
  const ext = extensionOf(sourcePath) || extensionOf(a.fileName ?? '');
  // A WhatsApp export already carries WhatsApp names; keep them unless the Telegram flavor must retype.
  if (fromWhatsApp && a.fileName && /^\d{8}-/.test(a.fileName)) {
    if (flavor === 'telegram') {
      const gif = /^(\d+)-GIF-(.*)\.mp4$/i.exec(a.fileName);
      if (gif) return `${gif[1]}-VIDEO-${gif[2]}.mp4`;
    }
    return sanitizeFileName(a.fileName, 200);
  }
  switch (a.kind) {
    case 'image':
      if (ext === 'jpg' || ext === 'jpeg') return `${seq}-PHOTO-${t}.jpg`;
      return `${seq}-PHOTO-${t}.${ext || 'jpg'}`;
    case 'video':
      return `${seq}-VIDEO-${t}.mp4`;
    case 'gif':
    case 'animation':
      return flavor === 'telegram' ? `${seq}-VIDEO-${t}.mp4` : `${seq}-GIF-${t}.mp4`;
    case 'voice':
      return `${seq}-AUDIO-${t}.opus`;
    case 'sticker':
      if (!animatedSticker) return `${seq}-STICKER-${t}.webp`;
      break;
    default:
      break;
  }
  const original = sanitizeFileName(a.fileName ?? sourcePath.split('/').pop() ?? 'file');
  const isJpeg = a.mimeType === 'image/jpeg' || ext === 'jpg' || ext === 'jpeg';
  return `${seq}-${neutralizeDocumentName(original, isJpeg)}`;
}

/** File-system-safe archive name, as WhatsApp names its exports. */
export function archiveName(title: string, suffix = ''): string {
  const safe = title.replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_').trim() || 'Chat';
  return `WhatsApp Chat - ${safe}${suffix}.zip`;
}
