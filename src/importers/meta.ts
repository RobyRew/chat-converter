async function parseJsonThread(t: ThreadFiles, platform: PlatformId, ctx: ParseContext): Promise<ThreadResult> {
  const people = new People(platform);
  const convId = conversationId(platform, `${t.folder}/${t.key}`);
  let title: string | undefined;
  const items: MetaJsonMessage[] = [];
  for (const page of t.pages) {
    let data: MetaJson;
    try {
      data = JSON.parse(await readText(page.file)) as MetaJson;
    } catch {
      ctx.warn(`${page.file.path} is not valid JSON; skipped`);
      continue;
    }
    const name = data.title ?? data.threadName;
    title ??= name ? fixMojibake(name) : undefined;
    for (const p of data.participants ?? []) {
      const n = typeof p === 'string' ? p : p.name;
      if (n) people.ensure(fixMojibake(n));
    }
    const list = data.messages ?? [];
    // DYI pages list the newest message first, the E2EE export the oldest; put them oldest first, then
    // order by time (a stable sort keeps same-millisecond messages in their written order).
    const chronological = list.length > 1 && stampOf(list[0]!) > stampOf(list[list.length - 1]!) ? [...list].reverse() : [...list];
    const sorted = chronological.sort((a, b) => stampOf(a) - stampOf(b));
    items.push(...sorted);
  }
  const messages: Message[] = items.map((m, index) => {
    const senderRaw = m.sender_name ?? m.senderName;
    const sender = senderRaw ? fixMojibake(senderRaw) : undefined;
    const ts = stampOf(m);
    const msg: Message = { id: messageId(convId, index, ts, sender ?? ''), ts, kind: 'text', raw: m };
    if (sender) msg.senderId = people.ensure(sender);
    let body = m.content ?? m.text;
    body = body ? fixMojibake(body) : '';
    const media: Array<{ path: string; hint?: string }> = [
      ...(m.photos ?? []).map((x) => ({ path: x.uri ?? '' })),
      ...(m.videos ?? []).map((x) => ({ path: x.uri ?? '' })),
      ...(m.audio_files ?? []).map((x) => ({ path: x.uri ?? '', hint: 'audio' })),
      ...(m.gifs ?? []).map((x) => ({ path: x.uri ?? '', hint: 'gif' })),
      ...(m.files ?? []).map((x) => ({ path: x.uri ?? '', hint: 'file' })),
      ...(m.media ?? []).map((x) => ({ path: x.uri ?? '' })),
      ...(m.sticker?.uri ? [{ path: m.sticker.uri, hint: 'sticker' }] : []),
    ].filter((x) => x.path);
    if (media.length) {
      msg.attachments = media.map((x) => attachment(x.path, `${convId}:${index}`, ctx, x.hint));
      msg.kind = media.some((x) => x.hint === 'sticker') ? 'sticker' : 'media';
    }
    let generated: string | undefined;
    if (m.share?.link || m.share?.share_text) {
      if (GENERATED_SHARE.test(body)) {
        generated = body;
        body = '';
      }
      const notes = [m.share.share_text, m.share.original_content_owner].filter((x): x is string => !!x).map(fixMojibake);
      const content = assemble(body ? { text: body, entities: [] } : undefined, notes, m.share.link);
      if (content) msg.content = content;
      msg.ext = { [platform]: { share: { url: m.share.link, notes }, ...(generated ? { generated } : {}) } };
    } else if (body) {
      msg.content = { text: body, entities: [] };
    }
    if (typeof m.call_duration === 'number' || m.type === 'Call') {
      msg.kind = 'call';
      const sec = m.call_duration ?? 0;
      msg.call = { durationSec: sec, ...(sec === 0 ? { reason: 'missed' } : {}), ...(body ? { label: body } : {}) };
    }
    if (m.type === 'Subscribe' || m.type === 'Unsubscribe') {
      msg.kind = 'service';
      msg.service = { action: m.type.toLowerCase(), data: { users: (m.users ?? []).map((u) => fixMojibake(u.name ?? '')) } };
    }
    if (m.is_unsent || m.isUnsent) msg.deleted = true;
    if (m.reactions?.length) {
      msg.reactions = m.reactions.map((r) => {
        const reaction: Reaction = { emoji: fixMojibake(r.reaction ?? '❤'), count: 1 };
        if (r.actor) reaction.senderId = people.ensure(fixMojibake(r.actor));
        if (typeof r.timestamp === 'number') reaction.ts = r.timestamp < 1e12 ? r.timestamp * 1000 : r.timestamp;
        return reaction;
      });
    }
    if (!msg.content && !media.length && msg.kind === 'text' && !msg.deleted) msg.meta = { contentUnavailable: true };
    return msg;
  });
  return { conversation: finish(convId, platform, t, people, messages, title, 'dyi-json') };
}

function stampOf(m: MetaJsonMessage): number {
  const v = m.timestamp_ms ?? m.timestamp ?? 0;
  return v < 1e12 ? v * 1000 : v;
}

// ---------- archive ----------

function finish(
  convId: string,
  platform: PlatformId,
  t: ThreadFiles,
  people: People,
  messages: Message[],
  title: string | undefined,
  format: 'dyi-html' | 'dyi-json',
): Conversation {
  const participants = [...people.map.values()];
  const conversation: Conversation = {
    schemaVersion: 2,
    id: convId,
    kind: participants.length > 2 ? 'group' : 'dm',
    originPlatform: platform,
    participants,
    messages,
    meta: { exportFormat: format, folder: t.folder },
    ext: { [platform]: { thread: t.key, folder: t.folder } },
  };
  if (title) conversation.title = title;
  return conversation;
}

/** The account owner takes part in every thread; the name present in the most threads is theirs. */
function guessOwner(conversations: Conversation[]): string | undefined {
  const counts = new Map<string, number>();
  for (const c of conversations) for (const p of c.participants) if (p.displayName) counts.set(p.displayName, (counts.get(p.displayName) ?? 0) + 1);
  let best: string | undefined;
  let n = 0;
  for (const [name, k] of counts) if (k > n) [best, n] = [name, k];
  return conversations.length > 1 && n >= Math.ceil(conversations.length * 0.6) ? best : undefined;
}

const formatOffset = (min: number): string => `${min < 0 ? '-' : '+'}${String(Math.floor(Math.abs(min) / 60)).padStart(2, '0')}:${String(Math.abs(min) % 60).padStart(2, '0')}`;

async function readAll(input: ImportInput, ctx: ParseContext, platform: PlatformId): Promise<Conversation[]> {
  const threads = findThreads(input.source, input.files);
  if (!threads.length) throw new ConversionError('No Meta message threads found (messages/inbox/…/message_1.html or .json)', 'NO_CHAT_FILE');
  const tz = ctx.timeZone ?? defaultTimeZone();
  const parsed: Conversation[] = [];
  let generatedBy: string | undefined;
  let generatedAt: ThreadResult['generatedAt'];
  for (const t of threads) {
    const r = t.format === 'json' ? await parseJsonThread(t, platform, ctx) : await parseHtmlThread(t, platform, ctx, tz);
    parsed.push(r.conversation);
    generatedBy ??= r.generatedBy;
    generatedAt ??= r.generatedAt;
  }
  const owner = generatedBy ?? guessOwner(parsed);
  if (owner) {
    for (const c of parsed) {
      const self = c.participants.find((p) => p.displayName === owner);
      if (self) c.selfId = self.id;
    }
  }
  if (generatedAt && threads.some((t) => t.format === 'html')) {
    const zone = zoneOffsetMinutes(generatedAt.utc, tz);
    if (zone !== generatedAt.offsetMinutes) {
      ctx.warn(
        `This export shows its times in UTC${formatOffset(generatedAt.offsetMinutes)} (on the day it was made); the time zone used, ${tz}, ` +
          `was UTC${formatOffset(zone)} then. Choose the zone the account used, or every time is off by the difference.`,
      );
    }
  }
  parsed.sort((a, b) => (b.messages.at(-1)?.ts ?? 0) - (a.messages.at(-1)?.ts ?? 0)); // latest activity first
  return parsed;
}

const caps: CapabilityMatrix = {
  timestamps: true,
  richText: true,
  reactions: true,
  media: true,
  calls: true,
  deletions: true,
  groups: true,
  multipleParticipants: true,
};

function createMetaImporter(platform: 'instagram' | 'messenger'): Importer {
  return {
    platform,
    capabilities: caps,
    async detect(input: ImportInput): Promise<DetectResult> {
      const threads = findThreads(input.source, input.files);
      const page = threads[0]?.pages[0]?.file;
      if (!page) return { platform, confidence: 0 };
      const which = whichMeta(input.source, input.files) ?? (await sniffPage(page));
      if (!which) return { platform, confidence: 0 };
      const reason = `${threads.length} ${platform === 'instagram' ? 'Instagram' : 'Messenger'} thread(s)`;
      return { platform, confidence: which !== platform ? 0 : threads[0]!.partial ? 0.85 : 0.97, reason };
    },
    async parse(input: ImportInput, ctx: ParseContext): Promise<Conversation> {
      const list = await readAll(input, ctx, platform);
      return list[0]!;
    },
    async parseArchive(input: ImportInput, ctx: ParseContext): Promise<Conversation[]> {
      return readAll(input, ctx, platform);
    },
  };
}

export const instagramImporter = createMetaImporter('instagram');
export const messengerImporter = createMetaImporter('messenger');
