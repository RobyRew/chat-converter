/** Meta's JSON writes UTF-8 bytes as Latin-1 escapes ("Ã©" for "é"); re-decode when that is what it is. */
const strictUtf8 = new TextDecoder('utf-8', { fatal: true });
export function fixMojibake(s: string): string {
  if (!/[\u0080-ÿ]/.test(s) || /[^\u0000-ÿ]/.test(s)) return s;
  try {
    return strictUtf8.decode(Uint8Array.from(s, (c) => c.charCodeAt(0)));
  } catch {
    return s;
  }
}

const MONTHS: Record<string, number> = {
  jan: 1, feb: 2, mar: 3, apr: 4, may: 5, jun: 6, jul: 7, aug: 8, sep: 9, sept: 9, oct: 10, nov: 11, dec: 12,
  ene: 1, abr: 4, ago: 8, dic: 12,
};

/** "Sep 08, 2025 10:15 am" (also "Sep 8, 2025, 10:15:03 AM", or inside parentheses) → wall clock. */
export function parseMetaDate(text: string): WallClock | null {
  const m = /([A-Za-z]{3,4})\.?\s+(\d{1,2}),?\s+(\d{4}),?\s+(\d{1,2}):(\d{2})(?::(\d{2}))?\s*([ap])\.?\s*m\.?/i.exec(text);
  if (!m) return null;
  const month = MONTHS[(m[1] ?? '').toLowerCase()];
  if (!month) return null;
  let hour = Number(m[4]) % 12;
  if ((m[7] ?? '').toLowerCase() === 'p') hour += 12;
  return { year: Number(m[3]), month, day: Number(m[2]), hour, minute: Number(m[5]), second: Number(m[6] ?? 0) };
}

/** "Duration: 9 minutes", "1 hour 2 minutes" → seconds. */
export function parseDuration(text: string): number | undefined {
  let total = 0;
  let found = false;
  for (const m of text.matchAll(/(\d+)\s*(hours?|hrs?|minutes?|mins?|seconds?|secs?)\b/gi)) {
    found = true;
    const n = Number(m[1]);
    const unit = (m[2] ?? '').toLowerCase();
    total += unit.startsWith('h') ? n * 3600 : unit.startsWith('m') ? n * 60 : n;
  }
  return found ? total : undefined;
}

/** The line Meta writes in place of a shared post's text. English only; other languages stay as text. */
const GENERATED_SHARE = /^.{1,80}? sent an attachment\.$/su;

function mediaKind(path: string, hint?: string): Attachment['kind'] {
  if (hint === 'gif') return 'gif';
  if (hint === 'sticker') return 'sticker';
  if (hint === 'file') return 'file';
  if (hint === 'audio' || /\/audio\//.test(path)) return 'voice';
  if (/\/gifs\//.test(path)) return 'gif';
  if (/\/(?:videos|video)\//.test(path)) return 'video';
  if (/\/(?:photos|images)\//.test(path)) return 'image';
  const ext = extensionOf(path);
  if (['jpg', 'jpeg', 'png', 'webp', 'heic'].includes(ext)) return 'image';
  if (['mp4', 'mov'].includes(ext)) return 'video';
  if (['m4a', 'aac', 'opus', 'ogg', 'mp3', 'wav'].includes(ext)) return 'voice';
  return 'file';
}

/**
 * The source path of a file Meta references by its path from the export root. When only part of the export
 * was dropped, the leading folders are gone from the source, so shorter tails of the path are tried.
 */
function resolveRef(path: string, ctx: ParseContext): string | undefined {
  if (ctx.media.has(path)) return path;
  const parts = path.split('/');
  for (let i = 1; i < parts.length; i++) {
    const tail = parts.slice(i).join('/');
    if (ctx.media.has(tail)) return tail;
  }
  return undefined;
}

function attachment(path: string, key: string, ctx: ParseContext, hint?: string): Attachment {
  const att: Attachment = { id: attachmentId(`${key}:${path}`), kind: mediaKind(path, hint), fileName: baseName(path) };
  if (/^https?:/i.test(path)) {
    att.present = false;
    att.omitted = 'unavailable';
    att.meta = { url: path };
    return att;
  }
  const local = resolveRef(path, ctx);
  att.ref = local ?? path;
  const size = local ? ctx.media.get(local)?.size : undefined;
  if (size !== undefined) att.size = size;
  if (local) att.present = true;
  else {
    att.present = false;
    att.omitted = 'missing';
  }
  return att;
}

/** "❤🇷🇴Ana Pop🇷🇴" → ❤ + "🇷🇴Ana Pop🇷🇴": the reaction is the first emoji, the rest is the actor's name. */
export function splitReaction(text: string): { emoji: string; name: string } {
  const m = /^(\p{Extended_Pictographic}(?:️|\p{Emoji_Modifier}|‍\p{Extended_Pictographic}️?)*|\S)\s*(.*)$/su.exec(text.trim());
  return { emoji: m?.[1] ?? text.trim(), name: (m?.[2] ?? '').trim() };
}

class People {
  readonly map = new Map<string, Participant>();
  constructor(private readonly platform: PlatformId) {}
  ensure(name: string): string {
    const id = participantId(this.platform, name);
    if (!this.map.has(id)) this.map.set(id, { id, displayName: name });
    return id;
  }
}

/** Text, then notes, then a link, one per line; the link becomes a link entity. */
function assemble(text: RichText | undefined, notes: string[], url?: string): RichText | undefined {
  let body = text?.text ?? '';
  const entities: MessageEntity[] = [...(text?.entities ?? [])];
  for (const n of notes) body = body ? `${body}\n${n}` : n;
  if (url) {
    if (body) body += '\n';
    entities.push({ type: 'link', offset: body.length, length: url.length });
    body += url;
  }
  return body ? { text: body, entities } : undefined;
}

// ---------- HTML ----------

function has(el: Element, token: string): boolean {
  return (el.attribs['class'] ?? '').split(/\s+/).includes(token);
}
/** Elements matching `pred`, outermost first; does not look inside a match. */
function all(node: { children: AnyNode[] }, pred: (e: Element) => boolean, out: Element[] = []): Element[] {
  for (const c of node.children) {
    if (!isTag(c)) continue;
    if (pred(c)) out.push(c);
    else all(c, pred, out);
  }
  return out;
}
function first(node: { children: AnyNode[] }, pred: (e: Element) => boolean): Element | undefined {
  return all(node, pred)[0];
}
function text(node: AnyNode): string {
  if (isText(node)) return node.data;
  if (!isTag(node)) return '';
  if (node.name === 'br') return '\n';
  return node.children.map(text).join('');
}
function ownText(el: Element): string {
  return el.children.filter(isText).map((t) => t.data).join('').trim();
}

const INLINE = new Set(['a', 'span', 'b', 'strong', 'i', 'em', 'u', 's', 'br', 'code', 'small']);
const MEDIA_TAGS = new Set(['img', 'video', 'audio']);
const isWebLink = (href: string): boolean => /^https?:/i.test(href);
const isLocalRef = (href: string): boolean => !!href && !/^[a-z][a-z0-9+.-]*:/i.test(href) && !href.startsWith('#');

function inlineOnly(el: Element): boolean {
  return el.children.every((c) => !isTag(c) || (INLINE.has(c.name) && inlineOnly(c)));
}

/** Inline content as rich text: `<br>` → newline, `<a href>` → link entity (UTF-16 offsets, after trimming). */
function runOf(el: Element): RichText {
  let out = '';
  const entities: MessageEntity[] = [];
  const walk = (n: AnyNode): void => {
    if (isText(n)) {
      out += n.data;
      return;
    }
    if (!isTag(n)) return;
    if (n.name === 'br') {
      out += '\n';
      return;
    }
    if (n.name === 'a') {
      const href = n.attribs['href'] ?? '';
      const label = text(n);
      const shown = label || href;
      const offset = out.length;
      out += shown;
      if (isWebLink(href) && shown) {
        entities.push(shown === href ? { type: 'link', offset, length: shown.length } : { type: 'link', offset, length: shown.length, url: href });
      }
      return;
    }
    n.children.forEach(walk);
  };
  el.children.forEach(walk);
  const lead = out.length - out.trimStart().length;
  const body = out.trim();
  return {
    text: body,
    entities: entities.map((e) => ({ ...e, offset: e.offset - lead })).filter((e) => e.offset >= 0 && e.offset + e.length <= body.length),
  };
}

export interface HtmlMessage {
  sender: string;
  date: string;
  text?: RichText;
  media: Array<{ path: string; hint?: string }>;
  share?: { url?: string; label?: string; notes: string[] };
  /** Meta's own line for a share ("X sent an attachment."), kept apart from the text. */
  generated?: string;
  call?: { durationSec: number; label?: string };
  reactions: Array<{ emoji: string; name: string; date?: string }>;
}

export function parseHtmlBlock(block: Element): HtmlMessage {
  const sender = text(first(block, (e) => has(e, '_a6-h')) ?? block).trim();
  const dateEl = first(block, (e) => has(e, '_a6-o'));
  const msg: HtmlMessage = { sender, date: dateEl ? text(dateEl).trim() : '', media: [], reactions: [] };
  const content = first(block, (e) => has(e, '_a6-p'));
  if (!content) return msg;

  for (const ul of all(content, (e) => e.name === 'ul')) {
    for (const li of all(ul, (e) => e.name === 'li')) {
      const span = first(li, (e) => e.name === 'span') ?? li;
      const when = first(span, (e) => e.name === 'span');
      const r = splitReaction(when ? ownText(span) : text(span));
      if (r.emoji) msg.reactions.push(when ? { ...r, date: text(when).replace(/[()]/g, '').trim() } : r);
    }
  }

  // Local files: img/video/audio sources and their <a> fallbacks, and linked documents.
  const seen = new Set<string>();
  for (const el of all(content, (e) => MEDIA_TAGS.has(e.name) || e.name === 'a' || e.name === 'ul')) {
    if (el.name === 'ul') continue;
    const src = el.attribs['src'] ?? el.attribs['href'] ?? '';
    if (!isLocalRef(src) || seen.has(src)) continue;
    seen.add(src);
    for (const inner of all(el, (e) => MEDIA_TAGS.has(e.name) || e.name === 'a')) {
      const s = inner.attribs['src'] ?? inner.attribs['href'];
      if (s) seen.add(s);
    }
    const hint = el.name === 'audio' ? 'audio' : el.name === 'a' && !all(el, (e) => MEDIA_TAGS.has(e.name)).length && !/\/(photos|videos|audio|gifs)\//.test(src) ? 'file' : undefined;
    msg.media.push(hint ? { path: src, hint } : { path: src });
  }

  const tags = content.children.filter(isTag);
  const slots = tags.length === 1 && tags[0]!.name === 'div' ? tags[0]!.children.filter(isTag) : tags;
  for (const s of slots) {
    if (all(s, (e) => e.name === 'ul' || MEDIA_TAGS.has(e.name)).length) continue;
    if (all(s, (e) => e.name === 'a' && isLocalRef(e.attribs['href'] ?? '')).length) continue;
    const idm = has(s, '_idm') ? s : first(s, (e) => has(e, '_idm'));
    if (idm) {
      const sec = parseDuration(text(idm));
      if (sec !== undefined) msg.call = { durationSec: sec };
      continue;
    }
    if (!text(s).trim()) continue;
    if (inlineOnly(s)) {
      const run = runOf(s);
      if (!msg.text && !msg.share) msg.text = run;
      else (msg.share ??= { notes: [] }).notes.push(run.text);
      continue;
    }
    // A share card (post, reel, story, profile): caption, owner and link, each in its own div.
    const share = (msg.share ??= { notes: [] });
    for (const line of all(s, (e) => e.name === 'div' && inlineOnly(e))) {
      const run = runOf(line);
      if (!run.text) continue;
      const link = first(line, (e) => e.name === 'a' && isWebLink(e.attribs['href'] ?? ''));
      if (link && text(link).trim() === run.text && share.url === undefined) {
        share.url = link.attribs['href']!;
        if (run.text !== share.url) share.label = run.text;
        continue;
      }
      share.notes.push(run.text);
    }
  }
  if (msg.share && msg.text && GENERATED_SHARE.test(msg.text.text)) {
    msg.generated = msg.text.text;
    delete msg.text;
  }
  if (msg.call && msg.text) msg.call.label = msg.text.text;
  return msg;
}

interface ThreadResult {
  conversation: Conversation;
  generatedBy?: string;
  /** Instant and UTC offset of the "Generated … UTC+02:00" footer of a Facebook page. */
  generatedAt?: { utc: number; offsetMinutes: number };
}

function generatedInfo(doc: { children: AnyNode[] }): Pick<ThreadResult, 'generatedBy' | 'generatedAt'> {
  const aside = first(doc, (e) => e.name === 'aside');
  if (!aside) return {};
  const out: Pick<ThreadResult, 'generatedBy' | 'generatedAt'> = {};
  const by = /Generated by (.+?) on\b/s.exec(text(aside));
  if (by?.[1]) out.generatedBy = by[1].trim();
  const time = first(aside, (e) => e.name === 'time');
  const utc = time?.attribs['datetime'] ? Date.parse(time.attribs['datetime']) : NaN;
  const off = /UTC([+-])(\d{1,2})(?::?(\d{2}))?/.exec(text(aside));
  if (Number.isFinite(utc) && off) {
    out.generatedAt = { utc, offsetMinutes: (off[1] === '-' ? -1 : 1) * (Number(off[2]) * 60 + Number(off[3] ?? 0)) };
  }
  return out;
}

async function parseHtmlThread(t: ThreadFiles, platform: PlatformId, ctx: ParseContext, tz: string): Promise<ThreadResult> {
  const people = new People(platform);
  const convId = conversationId(platform, `${t.folder}/${t.key}`);
  let title: string | undefined;
  let info: Pick<ThreadResult, 'generatedBy' | 'generatedAt'> = {};
  const raw: HtmlMessage[] = [];
  for (const page of t.pages) {
    const doc = parseDocument(await readText(page.file));
    if (title === undefined) {
      const h1 = first(doc, (e) => e.name === 'h1');
      if (h1) title = text(h1).trim();
      info = generatedInfo(doc);
    }
    const blocks = all(doc, (e) => has(e, '_a6-g'));
    for (let i = blocks.length - 1; i >= 0; i--) raw.push(parseHtmlBlock(blocks[i]!)); // newest first in the file
  }

  const clock = new WallClockSequence(tz);
  const messages: Message[] = [];
  raw.forEach((r, index) => {
    const wall = parseMetaDate(r.date);
    const ts = wall ? clock.at(wall) : (messages.at(-1)?.ts ?? 0);
    const msg: Message = { id: messageId(convId, index, r.sender, r.date), ts, kind: 'text' };
    const meta: Record<string, unknown> = {};
    if (wall) msg.tzOffsetMinutes = offsetOf(wall, ts);
    else meta['timeInferred'] = true;
    if (r.sender) msg.senderId = people.ensure(r.sender);
    const content = assemble(r.text, r.share?.notes ?? [], r.share?.url);
    if (content) msg.content = content;
    if (r.media.length) {
      msg.attachments = r.media.map((m) => attachment(m.path, `${convId}:${index}`, ctx, m.hint));
      msg.kind = 'media';
    }
    if (r.call) {
      msg.kind = 'call';
      msg.call = { durationSec: r.call.durationSec, ...(r.call.label ? { label: r.call.label, ...(/\bv[ií]deo\b/i.test(r.call.label) ? { video: true } : {}) } : {}) };
    }
    if (r.share || r.generated) {
      msg.ext = { [platform]: { ...(r.share ? { share: r.share } : {}), ...(r.generated ? { generated: r.generated } : {}) } };
    }
    if (!content && !r.media.length && !r.call) meta['contentUnavailable'] = true;
    if (r.reactions.length) {
      msg.reactions = r.reactions.map((x) => {
        const reaction: Reaction = { emoji: x.emoji, count: 1 };
        if (x.name) reaction.senderId = people.ensure(x.name);
        const when = x.date ? parseMetaDate(x.date) : null;
        if (when) reaction.ts = zonedTimeToUtc(when, tz);
        return reaction;
      });
    }
    if (Object.keys(meta).length) msg.meta = meta;
    messages.push(msg);
  });
  // Undated messages before the first dated one take its time.
  const firstDated = messages.find((m) => !m.meta?.['timeInferred']);
  if (firstDated) for (const m of messages) if (m.meta?.['timeInferred'] && m.ts === 0) m.ts = firstDated.ts;

  const conversation = finish(convId, platform, t, people, messages, title, 'dyi-html');
  conversation.meta = { ...conversation.meta, wallClockZone: tz };
  return { conversation, ...info };
}

