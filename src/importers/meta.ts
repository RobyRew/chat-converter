/*
 * Meta "Download your information": Instagram and Facebook Messenger, HTML or JSON.
 *
 * Layout (2025): <root>/your_instagram_activity/messages/<folder>/<thread>/message_N.(html|json) and
 * <root>/your_facebook_activity/messages/<folder>/<thread>/…, folders inbox, message_requests, archived_threads,
 * e2ee_cutover, filtered_threads; older exports put messages/ at the root. Each page lists the NEWEST message
 * first and message_1 is the newest page, so threads are read back to front.
 *
 * HTML (measured on a 2025-09 Instagram export, 92 threads / 31,251 blocks, and a Facebook one): a message is
 * an element with class token `_a6-g` (div on Instagram, section on Facebook) holding the sender (`_a6-h`),
 * the content (`_a6-p`) and the time (`_a6-o`, "Sep 08, 2025 10:15 am": minute precision, no zone). The
 * content is one div of slots: the text (inline: text, <br>, <a>), a share card (caption, owner, link as
 * separate divs; the text slot then holds Meta's "X sent an attachment."), media (img/video/audio with a
 * local src), a call duration (`span._idm` "Duration: 9 minutes") and the reactions (`ul._a6-q`, each
 * `<li><span>{emoji}{actor}<span> ({date})</span></span>`). Facebook pages also carry
 * `<aside>Generated by {owner} on <time datetime="…Z">… UTC+02:00</time></aside>`.
 *
 * JSON: {participants, messages[{sender_name, timestamp_ms, content, photos, videos, audio_files, gifs, files,
 * sticker, share, reactions, call_duration, is_unsent, type}], title}, UTF-8 text written as Latin-1 escapes;
 * Messenger's end-to-end-encrypted export uses camelCase keys (senderName, timestamp, text, media, isUnsent).
 */

const FOLDERS = 'inbox|message_requests|archived_threads|e2ee_cutover|filtered_threads';
const THREAD = new RegExp(`(?:^|/)messages/(${FOLDERS})/([^/]+)/message_(\\d+)\\.(html|json)$`);
/** Part of an export: an inbox/ folder, one thread folder, or the pages alone. */
const PARTIAL_THREAD = new RegExp(`(?:^|/)(?:(${FOLDERS})/)?([^/]+)/message_(\\d+)\\.(html|json)$`);
const BARE_PAGE = /^message_(\d+)\.(html|json)$/;

interface ThreadFiles {
  folder: string;
  key: string;
  pages: Array<{ n: number; file: SourceFile }>;
  format: 'html' | 'json';
  /** Found outside the full `…/messages/<folder>/<thread>/` layout. */
  partial: boolean;
}

type PageMatch = [folder: string, key: string, n: string, ext: string];

function findThreads(source: Pick<Source, 'name' | 'root'>, files: readonly SourceFile[]): ThreadFiles[] {
  const full = collectThreads(files, (f) => {
    const m = THREAD.exec(fullPath(source, f.path));
    return m ? [m[1] ?? '', m[2] ?? '', m[3] ?? '1', m[4] ?? 'html'] : null;
  }, false);
  if (full.length) return full;
  return collectThreads(files, (f) => {
    const m = PARTIAL_THREAD.exec(fullPath(source, f.path));
    if (m) return [m[1] ?? 'inbox', m[2] ?? '', m[3] ?? '1', m[4] ?? 'html'];
    const b = BARE_PAGE.exec(f.path);
    return b ? ['inbox', source.name, b[1] ?? '1', b[2] ?? 'html'] : null;
  }, true);
}

function collectThreads(files: readonly SourceFile[], match: (f: SourceFile) => PageMatch | null, partial: boolean): ThreadFiles[] {
  const map = new Map<string, ThreadFiles>();
  for (const f of files) {
    const m = match(f);
    if (!m) continue;
    const [folder, key, n, ext] = m;
    const id = `${folder}/${key}`;
    const t = map.get(id) ?? { folder, key, pages: [], format: ext as 'html' | 'json', partial };
    // When both variants exist, JSON wins (exact UTC times with seconds).
    if (t.format === 'html' && ext === 'json') {
      t.format = 'json';
      t.pages = [];
    }
    if (ext === t.format) t.pages.push({ n: Number(n), file: f });
    map.set(id, t);
  }
  for (const t of map.values()) t.pages.sort((a, b) => b.n - a.n); // oldest page first
  return [...map.values()];
}

function whichMeta(source: Pick<Source, 'root'>, files: readonly SourceFile[]): PlatformId | null {
  for (const f of files) {
    const p = fullPath(source, f.path);
    if (/(^|\/)your_instagram_activity\/messages\//.test(p)) return 'instagram';
    if (/(^|\/)your_facebook_activity\/messages\//.test(p)) return 'messenger';
  }
  return null;
}

/** For a page found outside the full layout: is it Meta's at all, and Instagram's or Facebook's? */
async function sniffPage(file: SourceFile): Promise<PlatformId | null> {
  const body = await readText(file);
  if (file.path.endsWith('.json')) {
    if (!/"(sender_name|senderName)"\s*:/.test(body)) return null;
    return /instagram/i.test(body.slice(0, 4096)) ? 'instagram' : 'messenger';
  }
  if (!/class="[^"]*\b_a6-g\b/.test(body)) return null;
  // Instagram pages carry its logo (files/Instagram-Logo.png, alt="Instagram"); Facebook's an inline image.
  return /Instagram-Logo|alt="Instagram"/.test(body) ? 'instagram' : 'messenger';
}

